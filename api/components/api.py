from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware

from components.routers import router


# =====================================================================
# 1. СОЗДАНИЕ ПРИЛОЖЕНИЯ
# =====================================================================

app = FastAPI(
    title="Equipment Maintenance API",
    version="1.0.0",
    description="Планирование ТОиР оборудования: справочники и реестр.",
)


# =====================================================================
# 2. MIDDLEWARE
# =====================================================================

# Для разработки — разрешаем всё. В проде сузить до конкретных origin.
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)


# =====================================================================
# 3. ПОДКЛЮЧЕНИЕ РОУТЕРОВ
# =====================================================================

app.include_router(router)


# =====================================================================
# 4. СЛУЖЕБНЫЕ ЭНДПОИНТЫ
# =====================================================================

@app.get("/health", tags=["service"])
def health():
    return {"status": "ok"}